  var supported = ["zh-CN", "en-US"];

  function valid(language) { return supported.indexOf(language) >= 0; }

  function detectLanguage(navigatorLanguage, storedLanguage) {
    if (valid(storedLanguage)) return storedLanguage;
    return /^en(?:-|$)/i.test(String(navigatorLanguage || "")) ? "en-US" : "zh-CN";
  }

  function interpolate(text, params) {
    params = params || {};
    return String(text).replace(/\{([A-Za-z0-9_]+)\}/g, function (all, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : all;
    });
  }

  function create(options) {
    options = options || {};
    var storage = options.storage || null;
    var storageKey = options.storageKey || "upsPod.language";
    var development = options.development !== false;
    var stored = null;
    try { stored = storage && storage.getItem(storageKey); } catch (ignoreRead) {}
    var active = detectLanguage(options.navigatorLanguage, stored);
    var listeners = [];

    function t(key, params) {
      var value = dictionaries[active][key];
      if (value === undefined) {
        if (development) throw new Error("Missing translation: " + key);
        value = dictionaries["zh-CN"][key];
        if (value === undefined) return "[" + key + "]";
      }
      return interpolate(value, params);
    }

    function setLanguage(language) {
      if (!valid(language)) throw new Error("Unsupported language: " + language);
      if (active === language) return false;
      active = language;
      try { if (storage) storage.setItem(storageKey, language); } catch (ignoreWrite) {}
      listeners.slice().forEach(function (listener) { listener(language); });
      return true;
    }

    function subscribe(listener) {
      if (typeof listener !== "function") throw new TypeError("listener must be a function");
      listeners.push(listener);
      return function () {
        var index = listeners.indexOf(listener);
        if (index >= 0) listeners.splice(index, 1);
      };
    }

    return {
      language: function () { return active; },
      t: t,
      setLanguage: setLanguage,
      subscribe: subscribe,
      formatTime: function (timestamp) { return new Date(timestamp).toLocaleTimeString(active); },
    };
  }

  return { dictionaries: dictionaries, detectLanguage: detectLanguage, create: create };
